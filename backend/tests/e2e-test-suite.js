// ─── CLEANUP ────────────────────────────────────────────────────────
async function cleanup() {
    section('🧹 CLEANUP — Removing all test data');

    // Use admin token for all cleanup (most permissions)
    const adminApi = api(state.tokens.admin);

    // 1. Delete registrations (by cancelling remaining ones)
    // Registrations are linked to events; deleting events should cascade
    // But let's cancel active registrations first to be safe
    for (const regId of state.registrationIds) {
        try {
            // Try to cancel if still active (participant might be needed)
            await api(state.tokens.participant1).patch(`/registrations/${regId}/cancel`);
        } catch (e) {
            // Already cancelled or other error — ignore
        }
    }
    console.log(`  🗑️  Attempted cancellation of ${state.registrationIds.length} registrations`);

    // 2. Delete events
    for (const eventId of state.eventIds) {
        try {
            // First try to set event back to draft (so it can be deleted)
            await adminApi.patch(`/events/${eventId}`, { status: 'draft' });
            await adminApi.delete(`/events/${eventId}`);
        } catch (e) {
            // If delete fails, try direct DB cleanup via admin
            try {
                await adminApi.delete(`/events/${eventId}`);
            } catch (e2) {
                console.log(`  ⚠️  Could not delete event ${eventId}: ${e2.response?.data?.message || e2.message}`);
            }
        }
    }
    console.log(`  🗑️  Attempted deletion of ${state.eventIds.length} events`);

    // 3. Delete organizer (via admin)
    if (state.userIds.organizer) {
        try {
            await adminApi.delete(`/admin/organizers/${state.userIds.organizer}`);
            console.log('  🗑️  Deleted test organizer');
        } catch (e) {
            console.log(`  ⚠️  Could not delete organizer: ${e.response?.data?.message || e.message}`);
        }
    }

    // 4. Delete participant users (direct DB cleanup via mongoose)
    // Since there's no API endpoint to delete participants, we'll use a direct DB approach
    console.log('  🗑️  Test participants require manual cleanup or a DB cleanup script');
    console.log('       Participant 1:', TEST_PARTICIPANT_1.email);
    console.log('       Participant 2:', TEST_PARTICIPANT_2.email);
    console.log('  💡  Run the cleanup script: node tests/cleanup-test-data.js');
}

