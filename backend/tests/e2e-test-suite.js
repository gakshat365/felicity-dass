// ─── Utilities ──────────────────────────────────────────────────────
let totalTests = 0;
let passed = 0;
let failed = 0;
const failures = [];

function api(token = null) {
    const instance = axios.create({ baseURL: BASE_URL });
    if (token) {
        instance.defaults.headers.common['Authorization'] = `Bearer ${token}`;
    }
    return instance;
}

async function test(name, fn) {
    totalTests++;
    const id = String(totalTests).padStart(2, '0');
    try {
        await fn();
        passed++;
        console.log(`  ✅ [${id}] ${name}`);
    } catch (err) {
        failed++;
        const msg = err.response?.data?.message || err.message || String(err);
        console.log(`  ❌ [${id}] ${name}`);
        console.log(`       → ${msg}`);
        if (err.response?.status) console.log(`       → HTTP ${err.response.status}`);
        failures.push({ id, name, error: msg });
    }
}

function assert(condition, message) {
    if (!condition) throw new Error(`Assertion failed: ${message}`);
}

function section(title) {
    console.log(`\n${'═'.repeat(60)}`);
    console.log(`  ${title}`);
    console.log(`${'═'.repeat(60)}`);
}

// ─── PHASE 1: Authentication & Security ─────────────────────────────
async function phase1_auth() {
    section('PHASE 1 — Authentication & Security');

    // 1. Admin login
    await test('Admin can log in', async () => {
        const { data } = await api().post('/auth/login', {
            email: ADMIN_EMAIL,
            password: ADMIN_PASSWORD
        });
        assert(data.token, 'No token returned');
        assert(data.role === 'admin', `Expected admin role, got ${data.role}`);
        state.tokens.admin = data.token;
        state.userIds.admin = data._id;
    });

    // 2. Register participant 1 (IIIT student)
    await test('Register participant (IIIT student email)', async () => {
        const { data } = await api().post('/auth/register', TEST_PARTICIPANT_1);
        assert(data.token, 'No token returned');
        assert(data.role === 'participant', `Expected participant, got ${data.role}`);
        state.tokens.participant1 = data.token;
        state.userIds.participant1 = data._id;
    });

    // 3. Register participant 2 (Outside IIIT)
    await test('Register participant (Outside IIIT email)', async () => {
        const { data } = await api().post('/auth/register', TEST_PARTICIPANT_2);
        assert(data.token, 'No token returned');
        state.tokens.participant2 = data.token;
        state.userIds.participant2 = data._id;
    });

    // 4. Duplicate registration blocked
    await test('Duplicate registration is blocked', async () => {
        try {
            await api().post('/auth/register', TEST_PARTICIPANT_1);
            throw new Error('Should have been rejected');
        } catch (err) {
            assert(err.response?.status === 400, `Expected 400, got ${err.response?.status}`);
        }
    });

    // 5. Login with wrong password
    await test('Login with wrong password is rejected', async () => {
        try {
            await api().post('/auth/login', {
                email: TEST_PARTICIPANT_1.email,
                password: 'WrongPassword123'
            });
            throw new Error('Should have been rejected');
        } catch (err) {
            assert(err.response?.status === 401, `Expected 401, got ${err.response?.status}`);
        }
    });

    // 6. Access protected route without token
    await test('Protected route rejects unauthenticated request', async () => {
        try {
            await api().get('/users/profile');
            throw new Error('Should have been rejected');
        } catch (err) {
            assert(err.response?.status === 401, `Expected 401, got ${err.response?.status}`);
        }
    });

    // 7. Get own profile (verifies JWT works)
    await test('Authenticated user can get profile (JWT works)', async () => {
        const { data } = await api(state.tokens.participant1).get('/auth/me');
        assert(data.email === TEST_PARTICIPANT_1.email, 'Email mismatch');
        assert(data.role === 'participant', 'Role mismatch');
    });

    // 8. Change password
    await test('User can change password', async () => {
        const { data } = await api(state.tokens.participant2).patch('/auth/change-password', {
            currentPassword: TEST_PARTICIPANT_2.password,
            newPassword: 'NewPass@789'
        });
        assert(data.message, 'No success message');
        // Login with new password
        const loginRes = await api().post('/auth/login', {
            email: TEST_PARTICIPANT_2.email,
            password: 'NewPass@789'
        });
        state.tokens.participant2 = loginRes.data.token;
    });

    // 9. Role-based access control — participant cannot access admin routes
    await test('RBAC: Participant cannot access admin routes', async () => {
        try {
            await api(state.tokens.participant1).get('/admin/stats');
            throw new Error('Should have been rejected');
        } catch (err) {
            assert([401, 403].includes(err.response?.status), `Expected 401/403, got ${err.response?.status}`);
        }
    });
}

