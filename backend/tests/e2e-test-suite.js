// ─── Configuration ──────────────────────────────────────────────────
const BASE_URL = process.env.TEST_BASE_URL || 'http://localhost:5000/api';
const ADMIN_EMAIL = process.env.TEST_ADMIN_EMAIL || 'admin@iiit.ac.in';
const ADMIN_PASSWORD = 'TestAdmin@123';  // We'll reset it to this

/**
 * Bootstrap: Connect to MongoDB and reset admin password to a known value,
 * so the test suite always starts with working admin credentials.
 */
async function bootstrapAdmin() {
    console.log('  🔧 Bootstrapping: Resetting admin password...');
    await mongoose.connect(process.env.MONGO_URI);
    const User = require('../models/User');
    const salt = await bcrypt.genSalt(10);
    const hash = await bcrypt.hash(ADMIN_PASSWORD, salt);
    const res = await User.updateOne(
        { email: ADMIN_EMAIL, role: 'admin' },
        { $set: { password: hash } }
    );
    if (res.modifiedCount === 0 && res.matchedCount === 0) {
        throw new Error('Admin account not found! Run: node scripts/createAdmin.js');
    }
    await mongoose.disconnect();
    console.log('  ✅ Admin password reset to known test value\n');
}

